export function openHelp() {
    const close = openSheet(h('div', {},
        h('div', { class: 'flex items-center justify-between' },
            h('h2', { class: 'text-lg font-bold' }, '操作説明'),
            h('button', { type: 'button', class: 'px-3 py-1 rounded-lg border border-border', onClick: () => close() }, '閉じる')),
        ...SECTIONS.map((section) => h('section', { class: 'mt-4' },
            h('h3', { class: 'font-bold text-primary' }, section.title),
            h('ul', { class: 'mt-1 grid gap-1 text-sm list-disc pl-5' },
                section.items.map((text) => h('li', {}, text)))))));
    window.lucide?.createIcons();
    return close;
}

export const helpIcon = () => icon('circle-help', 'w-5 h-5');
